print("Welcome to grade checker")

score = int(input("enter your score"))

if score > 90 : print("You got A grade")
elif (score >= 80 and score <= 89) : print("You got B grade")
elif (score >= 70 and score <= 79) : print("You got C grade")
elif (score >= 60 and score <= 69) : print("You got D grade")
elif (score <= 60) : print("You got F grade")
